create policy "Admins can read game media"
on storage.objects for select
to authenticated
using (
  bucket_id = 'game-media'
  and (select private.is_admin())
);

create policy "Admins can upload game media"
on storage.objects for insert
to authenticated
with check (
  bucket_id = 'game-media'
  and (storage.foldername(name))[1] = 'games'
  and (select private.is_admin())
);

create policy "Admins can update game media"
on storage.objects for update
to authenticated
using (
  bucket_id = 'game-media'
  and (select private.is_admin())
)
with check (
  bucket_id = 'game-media'
  and (storage.foldername(name))[1] = 'games'
  and (select private.is_admin())
);
