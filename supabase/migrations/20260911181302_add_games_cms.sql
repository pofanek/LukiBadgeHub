create schema if not exists private;

do $$
begin
  if not exists (
    select 1
    from pg_type
    where typnamespace = 'public'::regnamespace
      and typname = 'role'
  ) then
    create type public.role as enum ('User', 'Moderator', 'Admin');
  end if;
end;
$$;

alter table public.user_profiles
  add column if not exists role public.role not null default 'User';

create table if not exists public.games (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  name text not null,
  description text not null default '',
  game_creator text,
  icon_url text,
  thumbnail_url text
);

alter table public.games
  alter column description set default '',
  alter column game_creator drop not null,
  alter column icon_url drop not null,
  alter column thumbnail_url drop not null,
  add column if not exists developer text not null default '',
  add column if not exists publisher text not null default '',
  add column if not exists release_date date,
  add column if not exists genres text[] not null default '{}',
  add column if not exists steam_url text,
  add column if not exists cover_path text,
  add column if not exists cover_position text not null default 'center',
  add column if not exists banner_path text,
  add column if not exists is_published boolean not null default false,
  add column if not exists updated_at timestamptz not null default now();

do $$
begin
  if not exists (
    select 1
    from information_schema.columns
    where table_schema = 'public'
      and table_name = 'games'
      and column_name = 'id'
      and is_identity = 'YES'
  ) then
    alter table public.games
      alter column id add generated by default as identity;
  end if;

  if not exists (
    select 1
    from pg_constraint
    where conrelid = 'public.games'::regclass
      and conname = 'games_name_not_blank'
  ) then
    alter table public.games
      add constraint games_name_not_blank check (btrim(name) <> '');
  end if;
end;
$$;

create unique index if not exists games_name_lower_key
  on public.games (lower(name));

create index if not exists games_published_created_at_idx
  on public.games (created_at desc)
  where is_published;

create or replace function private.set_game_updated_at()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

revoke all on function private.set_game_updated_at() from public, anon, authenticated;

drop trigger if exists set_game_updated_at on public.games;
create trigger set_game_updated_at
before update on public.games
for each row execute function private.set_game_updated_at();

create or replace function private.is_admin()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select (select auth.uid()) is not null
    and exists (
      select 1
      from public.user_profiles
      where id = (select auth.uid())
        and role = 'Admin'::public.role
    );
$$;

revoke all on function private.is_admin() from public, anon;
grant execute on function private.is_admin() to authenticated;

